function applyHtmlLang(code: Lang) {
  try {
    document.documentElement.lang = code === 'zh' ? 'zh-Hans' : code === 'zh-Hant' ? 'zh-Hant' : 'en'
  } catch { /* ignore */ }
}

try {
  // Language follows country. Chinese browsers default to CN (not US+zh).
  const country = defaultCountry()
  const picked = persistCountry(country)
  lang.value = picked.h5Lang
  applyHtmlLang(lang.value)
  localStorage.setItem(LOCALE_STORAGE_KEY, lang.value)
  try { syncHarborLangCookie() } catch (_) {}
} catch {
  /* keep zh */
}

export function useI18n() {
  const t = (key: string, vars?: Record<string, string | number>) => {
      let out = dict[lang.value]?.[key] || (lang.value === 'zh-Hant' ? dict.zh[key] : undefined) || dict.en[key] || key
      if (vars) {
        for (const [k, v] of Object.entries(vars)) out = out.replace(new RegExp('\\{' + k + '\\}', 'g'), String(v))
      }
      return out
    }
  const catLabel = (id: string) => {
    const map: Record<string, { zh: string; 'zh-Hant': string; en: string }> = {
      kitchen: { zh: '厨房', 'zh-Hant': '廚房', en: 'Kitchen' },
      cleaning: { zh: '清洁', 'zh-Hant': '清潔', en: 'Clean' },
      storage: { zh: '收纳', 'zh-Hant': '收納', en: 'Store' },
      personal: { zh: '个护', 'zh-Hant': '個護', en: 'Care' },
      pet: { zh: '宠物', 'zh-Hant': '寵物', en: 'Pet' },
      office: { zh: '办公', 'zh-Hant': '辦公', en: 'Desk' },
      daily: { zh: '日用', 'zh-Hant': '日用', en: 'Home' },
      tableware: { zh: '餐具', 'zh-Hant': '餐具', en: 'Tableware' },
      paper: { zh: '纸品', 'zh-Hant': '紙品', en: 'Paper' },
      beauty: { zh: '护肤', 'zh-Hant': '護膚', en: 'Beauty' },
      makeup: { zh: '美妆', 'zh-Hant': '美妝', en: 'Makeup' },
      textile: { zh: '纺织', 'zh-Hant': '紡織', en: 'Textile' },
      decor: { zh: '装饰', 'zh-Hant': '裝飾', en: 'Decor' },
      appliance: { zh: '电器', 'zh-Hant': '電器', en: 'Appliance' },
      hardware: { zh: '工具', 'zh-Hant': '工具', en: 'Tools' },
      party: { zh: '派对', 'zh-Hant': '派對', en: 'Party' },
      All: { zh: '全部', 'zh-Hant': '全部', en: 'All' },
    }
    return map[id]?.[lang.value] || id
  }
  return {
    lang: computed(() => lang.value),
    t,
    catLabel,
    setLang: (l: Lang) => {
      lang.value = l
      applyHtmlLang(l)
      try {
        localStorage.setItem(LOCALE_STORAGE_KEY, l)
      } catch {
        /* ignore */
      }
      try {
        syncHarborLangCookie()
      } catch {
        /* ignore */
      }
    },
    /** Prefer this: language is derived from country. */
    setCountry: (country: string) => {
      const picked = persistCountry(country)
      lang.value = picked.h5Lang
      applyHtmlLang(picked.h5Lang)
      try {
        localStorage.setItem(LOCALE_STORAGE_KEY, picked.h5Lang)
      } catch {
        /* ignore */
      }
      return picked
    },
  }
}
