def heat_line(texts, heat) -> str:
    """Short card/API heat label for one storefront language."""
    try:
        n = int(heat or 0)
    except (TypeError, ValueError):
        n = 0
    pack = texts or UI["en"]
    template = pack.get("heat_label") or UI["en"]["heat_label"]
    return template.format(n=n)
